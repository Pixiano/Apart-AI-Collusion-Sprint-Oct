"""New gemma / timing / qwen3-14b cells (read-only on data/). Run from repo root:
.venv\\Scripts\\python.exe analysis\\new_runs.py   -> prints markdown and writes analysis/out/new_runs.md

Definitions (as in analysis/common.py and RESULTS_TABLE.md): index = (mean price - 10) / 45 over all firms present;
gate = base index rounds 16-30 >= 0.5; effect = branch index minus the SAME run's reference branch ('none', or
'none_nocomm' for comm-cut), rounds 31-60 unless stated; only branches with exactly 30 rows count;
bootstrap 95% over runs, 10000 resamples, seed 0.
"""
import glob
import os

from common import ROOT, OUT, bootstrap, fmt, rows, window_ci

D = lambda *p: os.path.join(ROOT, "data", *p)
OLD = [D("main", f"gemma4-12b_common_s{s}") for s in range(11, 21)]
NEW = [D("gemma_more", f"gemma4-12b_common_s{s}") for s in range(31, 41)]
out, counts, short = [], {}, []


def p(s=""):
    print(s)
    out.append(s)


def load(d, tag):
    """rows of d/tag, or None if missing; incomplete cells are noted in `short`."""
    f = os.path.join(d, tag, "rounds.jsonl")
    if not os.path.exists(f):
        return None
    try:
        r = rows(f)
    except ValueError:  # partial last line of a running folder
        return None
    counts.setdefault(tag, set()).add(d)
    return r


def gated(ds):
    g = []
    for d in ds:
        b = load(d, "base")
        if b is None or len(b) < 30:
            short.append((d, "base", None if b is None else len(b)))
            continue
        if window_ci(b, 16, 30) >= 0.5:
            g.append(d)
    return g


def eff(ds, tag, ref="none", lo=31, hi=60, skip=()):
    """list of (seed, effect) over runs where both branches have exactly 30 rows."""
    res = []
    for d in ds:
        a, r = load(d, tag), load(d, ref)
        if a is None or r is None:
            continue
        if len(a) != 30 or len(r) != 30:
            short.append((d, tag, len(a)))
            continue
        res.append((int(d.rsplit("_s", 1)[1]), window_ci(a, lo, hi) - window_ci(r, lo, hi)))
    return [x for x in res if x[0] not in skip]


def cell(res):
    if not res:
        return "not run"
    m, a, b = bootstrap([v for _, v in res])
    return f"{fmt(m, 3, True)} ({fmt(a, 3, True)}, {fmt(b, 3, True)}), n={len(res)}" if len(res) > 1 else f"{fmt(m, 3, True)}, n=1"


def table(head, rowsl):
    p("| " + " | ".join(head) + " |\n|" + "---|" * len(head))
    for r in rowsl:
        p("| " + " | ".join(r) + " |")
    p()


g_old, g_new = gated(OLD), gated(NEW)
g_all = g_old + g_new
sets = {"20 seeds (11-20 + 31-40)": (g_all, len(OLD) + len(NEW)), "new seeds 31-40": (g_new, len(NEW)),
        "old seeds 11-20": (g_old, len(OLD))}

# ---- 1
p("# New runs (generated by analysis/new_runs.py)\n")
p("## 1. Gemma main study, effect vs same run's no-swap branch, rounds 31-60\n")
BR = ["clone_k1_hid", "family_k1_hid", "undercutter_k1_hid", "undercutter_k2_hid", "clone_k1_ann", "undercutter_k1_ann"]
rl = []
for name, (g, n) in sets.items():
    base = [window_ci(load(d, "base"), 16, 30) for d in g]
    ns = [window_ci(load(d, "none"), 31, 60) for d in g if load(d, "none") and len(load(d, "none")) == 30]
    rl.append([name, f"{len(g)} / {n}", fmt(sum(base) / len(base), 3), f"{fmt(sum(ns) / len(ns), 3)} (n={len(ns)})"]
              + [cell(eff(g, b)) for b in BR])
table(["seeds", "gated / runs", "base idx 16-30 (gated)", "no-swap idx 31-60"] + BR, rl)
ba = [window_ci(load(d, "base"), 16, 30) for d in OLD + NEW if load(d, "base")]
p(f"Base index 16-30 over ALL 20 base runs (gated or not): {fmt(sum(ba) / len(ba), 3)} (n={len(ba)}). "
  f"Ungated seeds: {[int(d.rsplit('_s', 1)[1]) for d in OLD + NEW if d not in g_all]}\n")

# ---- 2
p("## 2. Messages cut at the swap (reference = same run's none_nocomm), rounds 31-60\n")
rl = []
for name, g in (("old 11-20", g_old), ("new 31-40", g_new), ("pooled", g_all)):
    rl.append([name, cell(eff(g, "clone_k1_hid_nocomm", "none_nocomm")),
               cell(eff(g, "none_nocomm", "none")), cell(eff(g, "undercutter_k1_hid_nocomm", "none_nocomm"))])
table(["seeds", "clone, comm cut", "cut alone vs messages on (none_nocomm - none)", "undercutter k=1, comm cut (old only)"], rl)
for name, g in (("old", g_old), ("new", g_new)):
    p(f"Per-seed comm-cut clone effects ({name}): " + ", ".join(f"s{s}: {fmt(v, 3, True)}" for s, v in eff(g, "clone_k1_hid_nocomm", "none_nocomm")))
p()

# ---- 3
p("## 3. Entry (one or two new firms D, E at round 31; index over all firms present)\n")
rl = []
for tag in ("entry_k1_hid", "entry_k2_hid"):
    for name, g in (("old", g_old), ("new", g_new), ("pooled", g_all)):
        rl.append([tag, name, cell(eff(g, tag)), cell(eff(g, tag, lo=46, hi=60))])
table(["branch", "seeds", "rounds 31-60", "rounds 46-60"], rl)

# ---- 4
p("## 4. Newcomer myopic (rounds 31-60)\n")
rl = []
for name, g in (("old 11-20", g_old), ("new 31-40", g_new), ("pooled", g_all)):
    rl.append([name, cell(eff(g, "newcomer_myopic_k1_hid")), cell(eff(g, "newcomer_myopic_k1_hid", skip=(14,)))])
table(["seeds", "myopic, all", "myopic, without seed 14"], rl)
p("Per-seed: " + ", ".join(f"s{s}: {fmt(v, 3, True)}" for s, v in eff(g_all, "newcomer_myopic_k1_hid")) + "\n")

# ---- 5
p("## 5. Swap timing (index over the first 15 rounds after the swap; branch minus same checkpoint's none)\n")
gate_by_seed = {int(d.rsplit("_s", 1)[1]): d for d in g_old}
rl, per = [], {}
for t, lo, hi in ((15, 16, 30), (45, 46, 60)):
    for br in ("clone_k1_hid", "undercutter_k1_hid"):
        res = []
        for d in sorted(glob.glob(D("gemma_timing", f"gemma4-12b_common_s*_t{t}"))):
            s = int(d.split("_s")[-1].split("_t")[0])
            if s not in gate_by_seed:
                continue  # not gated in main base (gate taken from the matching main base run)
            a, r = load(d, br), load(d, "none")
            need = 30 if t == 15 else 15
            if a is None or r is None or len(a) != need or len(r) != need:
                short.append((d, br, None if a is None else len(a)))
                continue
            res.append((s, window_ci(a, lo, hi) - window_ci(r, lo, hi)))
        per[(t, br)] = res
for br in ("clone_k1_hid", "undercutter_k1_hid"):
    res30 = eff(g_old, br, lo=31, hi=45)
    rl.append([br, cell(per[(15, br)]), cell(res30), cell(per[(45, br)])])
table(["branch", "t=15 (rounds 16-30)", "t=30 (rounds 31-45, data/main)", "t=45 (rounds 46-60)"], rl)
p("Note: t=15 swap effect is measured over rounds 16-30 (first 15 rounds after the swap), t=45 over 46-60. "
  "Gate for the timing seeds = the matching data/main base run (rounds 16-30 >= 0.5); the timing folders hold no base run.\n")
for k, v in per.items():
    p(f"- t={k[0]} {k[1]}: " + ", ".join(f"s{s}: {fmt(x, 3, True)}" for s, x in v))
p()

# ---- 6
p("## 6. qwen3-14b as base (data/qwen14_more, finished bases only)\n")
rl, passed, fin = [], 0, 0
for d in sorted(glob.glob(D("qwen14_more", "qwen3-14b_common_s*"))):
    b = load(d, "base")
    s = d.rsplit("_s", 1)[1]
    if b is None or len(b) < 30:
        rl.append([s, "unfinished" if b is not None else "no base", "", "", ""])
        continue
    fin += 1
    gi = window_ci(b, 16, 30)
    passed += gi >= 0.5
    w = [r for r in b if r["round"] >= 16]
    lowr = lambda rs: sum(max(r["prices"]) <= 11 for r in rs) / len(rs)
    rl.append([s, fmt(gi, 3), fmt(10 + 45 * gi, 1), fmt(lowr(w), 2), "pass" if gi >= 0.5 else "fail"])
table(["seed", "gate idx 16-30", "mean price 16-30", "share of rounds 16-30 with all three <= 11", "gate"], rl)
p(f"Finished bases: {fin}; pass the gate: {passed}.\n")

# ---- sanity
p("## Sanity\n")
p("Folders with a rounds.jsonl found, per cell (gemma 20 seeds + timing + qwen14 pooled by tag name): " +
  ", ".join(f"{k}: {len(v)}" for k, v in sorted(counts.items())) + "\n")
bad = [(os.path.relpath(d, ROOT), t, n) for d, t, n in short]
p("Cells excluded as incomplete or short (path, cell, rows): " + (str(bad) if bad else "none") + "\n")
os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "new_runs.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
